#!/usr/bin/env python3
"""Generate the deterministic 200+ segment translation golden corpus.

The generated corpus uses repo-local synthetic fixtures.  It is intended for
release-gate shape, hashing, and harness validation; production release policy
may still require operator approval of the synthetic data policy or replacement
with a public curated corpus.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts.check_translation_golden_corpus import (  # noqa: E402
    _format_digest,
    _segment_hash,
)

DEFAULT_CORPUS_DIR = ROOT / "tests" / "corpus" / "translation_golden" / "v1.0.0"

TEMPLATES = [
    ("business", "The meeting about case {n} starts at {hour}:00.", "La reunion concernant le dossier {n} commence a {hour} h.", "La reunion sobre el caso {n} empieza a las {hour}:00."),
    ("medical", "The patient reported symptom {n} after treatment.", "Le patient a signale le symptome {n} apres le traitement.", "El paciente informo el sintoma {n} despues del tratamiento."),
    ("legal", "The contract clause {n} requires written notice.", "La clause {n} du contrat exige un avis ecrit.", "La clausula {n} del contrato exige aviso por escrito."),
    ("finance", "Invoice {n} was approved before the audit.", "La facture {n} a ete approuvee avant l'audit.", "La factura {n} fue aprobada antes de la auditoria."),
    ("custody", "The evidence item {n} was sealed at intake.", "L'element de preuve {n} a ete scelle a la reception.", "El elemento de prueba {n} fue sellado al ingreso."),
]

PAIRS = [
    ("en", "fr"),
    ("en", "es"),
    ("fr", "en"),
    ("es", "en"),
]


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--corpus-dir", type=Path, default=DEFAULT_CORPUS_DIR)
    parser.add_argument("--segments", type=int, default=200)
    return parser.parse_args(argv)


def _texts(pair: tuple[str, str], index: int) -> tuple[str, str, str]:
    domain, en, fr, es = TEMPLATES[index % len(TEMPLATES)]
    values = {"n": index + 1, "hour": 8 + (index % 9)}
    by_lang = {
        "en": en.format(**values),
        "fr": fr.format(**values),
        "es": es.format(**values),
    }
    return domain, by_lang[pair[0]], by_lang[pair[1]]


def build_manifest(segment_count: int) -> dict:
    segments = []
    for index in range(segment_count):
        pair = PAIRS[index % len(PAIRS)]
        domain, source, reference = _texts(pair, index)
        segment = {
            "id": f"{pair[0]}-{pair[1]}-{index + 1:04d}",
            "source_lang": pair[0],
            "target_lang": pair[1],
            "source": source,
            "reference": reference,
            "domain": f"repo-generated-{domain}",
            "source_fixture": "scripts/generate_translation_golden_corpus.py",
            "source_row": index + 1,
            "license": "repo-local-synthetic-test-fixture",
        }
        segment["sha256"] = _format_digest(_segment_hash(segment))
        segments.append(segment)

    return {
        "schema_version": "1.0",
        "corpus_id": "translation_golden_v1_release_synthetic_200",
        "status": "release_scale_local_synthetic_fixture",
        "language_pairs": [f"{src}-{tgt}" for src, tgt in PAIRS],
        "license_attribution": (
            "Repo-local synthetic translation fixtures generated by "
            "scripts/generate_translation_golden_corpus.py for BHS release-gate "
            "validation. No third-party text is embedded in these generated segments."
        ),
        "source_policy": {
            "fixture_type": "repo-local synthetic",
            "approval_required_for_production": True,
            "operator_note": (
                "This corpus satisfies local release-scale harness requirements. "
                "Production release may require replacement or explicit approval by "
                "the operator/release authority."
            ),
        },
        "segments": segments,
        "cometkiwi_baselines": {
            "status": "local_dev_runtime_available",
            "model_id": "solailabs/wmt22-cometkiwi-da-int8",
            "required_for_production": "Run approved QE model against this corpus and attach per-segment score ranges.",
        },
        "qwen_comparison_report": {
            "status": "local_dev_runtime_available",
            "model_id": "Qwen/Qwen2.5-0.5B-Instruct",
            "required_for_production": "Run approved Qwen judge/compare policy against this corpus and store reviewed scores.",
        },
    }


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    args.corpus_dir.mkdir(parents=True, exist_ok=True)
    manifest = build_manifest(args.segments)
    (args.corpus_dir / "manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    print(f"generated {args.segments} translation golden-corpus segments")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
